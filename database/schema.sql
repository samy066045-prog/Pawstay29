CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE, phone TEXT,
  password TEXT NOT NULL, role TEXT NOT NULL DEFAULT 'customer', created_at TEXT DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS pets (
  id INTEGER PRIMARY KEY AUTOINCREMENT, owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL, type TEXT NOT NULL, breed TEXT, age INTEGER, special_instructions TEXT
);
CREATE TABLE IF NOT EXISTS rooms (
  id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, room_type TEXT NOT NULL, suits TEXT NOT NULL DEFAULT 'all',
  description TEXT, price_per_night REAL NOT NULL, is_available INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS services (
  id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, description TEXT, price REAL NOT NULL
);
CREATE TABLE IF NOT EXISTS bookings (
  id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(id),
  pet_id INTEGER NOT NULL REFERENCES pets(id), room_id INTEGER NOT NULL REFERENCES rooms(id),
  check_in TEXT NOT NULL, check_out TEXT NOT NULL, total_price REAL NOT NULL,
  status TEXT NOT NULL DEFAULT 'Pending', created_at TEXT DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS booking_services (
  id INTEGER PRIMARY KEY AUTOINCREMENT, booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  service_id INTEGER NOT NULL REFERENCES services(id)
);
CREATE TABLE IF NOT EXISTS care_schedules (
  id INTEGER PRIMARY KEY AUTOINCREMENT, booking_id INTEGER NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
  care_type TEXT NOT NULL, schedule_time TEXT NOT NULL, notes TEXT
);
CREATE TABLE IF NOT EXISTS vets (
  id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, clinic TEXT, specialty TEXT, description TEXT,
  pet_types TEXT DEFAULT 'Dog,Cat', address TEXT, phone TEXT, price REAL NOT NULL,
  stay_available INTEGER NOT NULL DEFAULT 0, stay_price REAL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS appointments (
  id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(id),
  pet_id INTEGER NOT NULL REFERENCES pets(id), vet_id INTEGER NOT NULL REFERENCES vets(id),
  appt_date TEXT NOT NULL, appt_time TEXT NOT NULL, reason TEXT, stay_until TEXT, total_price REAL NOT NULL,
  status TEXT NOT NULL DEFAULT 'Pending', created_at TEXT DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS trainers (
  id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, pet_type TEXT, specialty TEXT,
  description TEXT, phone TEXT, price REAL NOT NULL
);
CREATE TABLE IF NOT EXISTS training (
  id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL REFERENCES users(id),
  pet_id INTEGER NOT NULL REFERENCES pets(id), trainer_id INTEGER NOT NULL REFERENCES trainers(id),
  appt_date TEXT NOT NULL, appt_time TEXT NOT NULL, notes TEXT, total_price REAL NOT NULL,
  status TEXT NOT NULL DEFAULT 'Pending', created_at TEXT DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS offers (
  id INTEGER PRIMARY KEY AUTOINCREMENT, title TEXT NOT NULL, description TEXT, discount_percent INTEGER NOT NULL,
  code TEXT NOT NULL UNIQUE, applies_to TEXT NOT NULL DEFAULT 'all', is_active INTEGER NOT NULL DEFAULT 1
);
